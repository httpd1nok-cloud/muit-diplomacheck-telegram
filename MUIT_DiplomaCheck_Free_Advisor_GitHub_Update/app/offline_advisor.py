def explain(question: str, lang: str = 'kk', domain: str | None = None) -> str:
    """Return useful task steps, examples, and only source-verified clause references."""
    lang='ru' if lang=='ru' else 'kk'
    which=intent(question)
    info=TOPICS[which]
    title,requirement,steps=info[lang]
    result=[f'📘 {title}', '', f'📚 {requirement}', '',
            '✅ Не істеу керек:' if lang=='kk' else '✅ Что сделать:']
    result.extend(f'• {step}' for step in steps)
    chosen=infer_domain(question) or (domain if domain in DOMAIN_EXAMPLES else None)
    if chosen and which in {'practical','experiment','calculations','plan','methods','general','theory'}:
        heading,examples=DOMAIN_EXAMPLES[chosen][lang]
        result.extend(['',f'🔧 {heading}'])
        result.extend('• '+e for e in examples)
    valid_db=clauses()
    numbers=[ref for ref in info['refs'] if ref in valid_db]
    if which=='theory' and '6.15' in valid_db:numbers.append('6.15')
    result.extend(['',('📖 Методичка тармақтары: ' if lang=='kk' else '📖 Пункты методички: ')+', '.join('§'+ref for ref in dict.fromkeys(numbers))])
    if which in {'practical','experiment','calculations','general','plan','methods'}:
        result.append('💬 Тақырыпты немесе қолданатын технологияңызды нақтыласаңыз, осы жоспарды соған бейімдеп беремін.' if lang=='kk' else '💬 Напишите точную тему или выбранную технологию — подберу более подходящий пример.')
    result.append('Ескерту: бұл — методичкаға сүйенген үлгі/кеңес, кафедраның бекітілген жоспары емес (2020 жылғы редакция).' if lang=='kk' else 'Примечание: рекомендации и примеры — не обязательный шаблон кафедры (редакция методички 2020 года).')
    return '\n'.join(result)
