@lru_cache(maxsize=1)
def clauses() -> dict:
    return json.loads((ROOT / 'config' / 'guide_clauses.json').read_text(encoding='utf-8'))


def find_topic(question: str) -> str | None:
    lowered = question.casefold()
    scores = {name:sum(2 if len(k)>=5 else 1 for k in d['keys'] if k in lowered) for name,d in TOPICS.items()}
    selected = max(scores, key=scores.get)
    return selected if scores[selected] else None


def retrieve(question: str, top_k: int = 5) -> list[dict]:
    """Get truthful PDF excerpts; deterministic, no API and no fabricated citations."""
    db = clauses()
    topic = find_topic(question)
    prioritized = list(TOPICS[topic]['clauses']) if topic else ['6.5','6.2','6.3','7.1','7.2']
    # Explicit clause numbers in the user's question outrank keyword matches.
    mentioned = [x for x in re.findall(r'(?<!\d)(\d{1,2}\.\d{1,2})(?!\d)', question) if x in db]
    selected = []
    for number in mentioned + prioritized:
        if number in db and number not in selected:
            selected.append(number)
        if len(selected)>=top_k:
            break
    return [db[num] for num in selected]


